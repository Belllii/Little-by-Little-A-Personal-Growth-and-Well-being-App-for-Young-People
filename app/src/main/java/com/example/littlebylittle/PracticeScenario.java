package com.example.littlebylittle;

import java.io.Serializable;

public class PracticeScenario implements Serializable {

    private final int id;
    private final String title;
    private final String category;
    private final String description;
    private final String[] options;
    private final String[] feedback;
    private final boolean isAutoGenerated;

    public PracticeScenario(int id, String title, String category, String description,
                            String[] options, String[] feedback, boolean isAutoGenerated) {
        this.id = id;
        this.title = title;
        this.category = category;
        this.description = description;
        this.options = options;
        this.feedback = feedback;
        this.isAutoGenerated = isAutoGenerated;
    }

    public int getId() {
        return id;
    }

    public String getTitle() {
        return title;
    }

    public String getCategory() {
        return category;
    }

    public String getDescription() {
        return description;
    }

    public String[] getOptions() {
        return options;
    }

    public String[] getFeedback() {
        return feedback;
    }

    public boolean isAutoGenerated() {
        return isAutoGenerated;
    }
}
